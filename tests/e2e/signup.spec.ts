import { randomBytes } from "node:crypto";
import { expect, test } from "@playwright/test";
test("mobile signup validates confirmation, supports visibility and accepts a ten-character password", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/sign-in");
  await expect(page.getByLabel("Confirm password", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Need an account? Sign up" }).click();
  const email = `signup-${randomBytes(8).toString("hex")}@example.com`;
  const password = randomBytes(5).toString("hex");
  const primary = page.getByLabel("Password", { exact: true });
  const confirm = page.getByLabel("Confirm password", { exact: true });
  await page.getByLabel("Email", { exact: true }).fill(email);
  await expect(primary).toHaveAttribute("minlength", "10");
  await expect(primary).toHaveAttribute("autocomplete", "new-password");
  await primary.fill("123456789"); await confirm.fill("123456789");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  expect(await primary.evaluate((input: HTMLInputElement) => input.validity.tooShort)).toBe(true);
  await expect(page).toHaveURL(/\/sign-in$/);
  await primary.fill(password); await confirm.fill(`${password}x`);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Passwords do not match" })).toBeVisible();
  await expect(confirm).toBeFocused(); await expect(confirm).toHaveAttribute("aria-invalid", "true");
  await expect(primary).toHaveAttribute("type", "password");
  await page.getByRole("button", { name: "Show password", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(primary).toHaveAttribute("type", "text");
  await expect(primary).toHaveAttribute("spellcheck", "false");
  await page.getByRole("button", { name: "Hide password", exact: true }).click();
  await expect(primary).toHaveAttribute("type", "password");
  await page.getByRole("button", { name: "Show confirm password", exact: true }).click();
  await expect(confirm).toHaveAttribute("type", "text");
  await confirm.fill(password);
  await expect(confirm).not.toHaveAttribute("aria-invalid", "true");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page).toHaveURL(/\/sign-in$/);
  await expect(confirm).toHaveCount(0);
  await expect(primary).toHaveAttribute("autocomplete", "current-password");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await primary.fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
});
