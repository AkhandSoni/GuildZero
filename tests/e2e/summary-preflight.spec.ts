import { randomBytes } from "node:crypto";
import { expect, test } from "@playwright/test";

test("strict summary preflight preserves draft CSV and blocks commitment until selected columns are corrected", async ({ page }) => {
  test.setTimeout(90000);
  await page.goto("/sign-in");
  await page.getByRole("button", { name: "Need an account? Sign up" }).click();
  await page.getByLabel("Email", { exact: true }).fill(`preflight-${randomBytes(8).toString("hex")}@example.com`);
  const password = randomBytes(24).toString("base64url");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/missions/new");
  const csv = 'price,units\n"$1,234.50",3\n"1234,50",-2';
  await page.getByLabel("Mission title", { exact: true }).fill("Strict format correction");
  await page.getByLabel("CSV dataset", { exact: true }).fill(csv);
  await page.getByRole("checkbox", { name: "price", exact: true }).check();
  await page.getByRole("checkbox", { name: "units", exact: true }).check();
  const requirements = page.getByLabel("Summary input requirements", { exact: true });
  await expect(requirements).toContainText('Column "price": unsupported numeric input in CSV records 2, 3.');
  await expect(requirements).toContainText("decimal commas and percentages are not converted");
  await expect(page.getByLabel("CSV dataset", { exact: true })).toHaveValue(csv);
  await page.getByRole("button", { name: "Create private mission", exact: true }).click();
  await expect(page).toHaveURL(/\/missions\/(?!new$)[a-z0-9]+$/);
  await expect(page.getByRole("button", { name: "Open auction", exact: true })).toBeDisabled();
  await expect(page.getByRole("alert").filter({ hasText: "Correct summary input before opening" })).toContainText('Column "price"');
  await page.reload();
  await expect(page.getByRole("button", { name: "Open auction", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Edit mission", exact: true }).click();
  await expect(page.getByLabel("CSV dataset", { exact: true })).toHaveValue(csv);
  await page.getByRole("checkbox", { name: "price", exact: true }).uncheck();
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByTestId("saved-options")).toHaveText("units");
  await expect(page.getByRole("button", { name: "Open auction", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Open auction", exact: true }).click();
  await expect(page.getByText("Main analysis · Work accepted", { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole("region", { name: "Summary result", exact: true }).getByRole("row", { name: "units 2 0 -2 3 1 0.5", exact: true })).toBeVisible();
  await expect(page.getByText("Sum is the sum of the selected column", { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: "Prepare exact payment", exact: true })).toBeVisible();
});
