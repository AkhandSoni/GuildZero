import { randomBytes } from "node:crypto";
import { acknowledgePreview } from "./helpers";
import { expect, test } from "@playwright/test";
test("owner confirms content removal for unawarded work and removed source cannot be reused", async ({ page }) => {
  await page.goto("/sign-in");
  await page.getByRole("button", { name: "Need an account? Sign up" }).click();
  await page.getByLabel("Email", { exact: true }).fill(`retention-${randomBytes(8).toString("hex")}@example.com`);
  const password = randomBytes(24).toString("base64url");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/missions/new");
  await page.getByLabel("Mission title").fill("Synthetic retention example");
  await page.getByLabel("CSV dataset").fill("units\n12345");
  await page.getByRole("checkbox", { name: "units", exact: true }).check();
  await page.getByLabel("Maximum budget (testnet NEAR)").fill("0.000000000000000000000001");
  await page.getByRole("button", { name: "Create private mission" }).click();
  await expect(page).toHaveURL(/\/missions\/(?!new$)[a-z0-9]+$/);
  await acknowledgePreview(page);
  await page.getByRole("button", { name: "Open auction", exact: true }).click();
  await expect(page.getByText("Main analysis · No eligible offer", { exact: true })).toBeVisible({ timeout: 15000 });
  const remove = page.getByRole("button", { name: "Remove dataset and outputs", exact: true });
  await expect(remove).toBeEnabled();
  await remove.click();
  await page.getByRole("button", { name: "Keep content", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Synthetic retention example", exact: true })).toBeVisible();
  await remove.click();
  await page.getByRole("button", { name: "Confirm permanent removal", exact: true }).click();
  await expect(page.getByText(/Content removed on/)).toBeVisible();
  await expect(page.getByRole("heading", { name: "Private content removed", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Use as new mission", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Prepare exact payment", exact: true })).toBeDisabled();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Content removed by owner", exact: true })).toBeVisible();
  await page.getByText("Input CSV · view saved source").click();
  await expect(page.getByText("Input removed by owner.", { exact: true })).toBeVisible();
  expect(await page.locator("body").innerText()).not.toContain("12345");
});
