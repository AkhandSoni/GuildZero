import { randomBytes } from "node:crypto";
import { expect, test } from "@playwright/test";

test("unsaved brief protects links, Back, reload and cancel; saves release the guard", async ({ page }) => {
  await page.goto("/sign-in");
  await page.getByRole("button", { name: "Need an account? Sign up" }).click();
  await page.getByLabel("Email", { exact: true }).fill(`unsaved-${randomBytes(8).toString("hex")}@example.com`);
  const password = randomBytes(24).toString("base64url");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole("link", { name: "+ New mission", exact: true }).click();
  await expect(page).toHaveURL(/\/missions\/new$/);
  const title = page.getByLabel("Mission title");
  await title.fill("Keep these edits");
  const dataset = page.getByLabel("CSV dataset", { exact: true });
  await dataset.fill("units\n3");
  page.once("dialog", async dialog => { expect(dialog.message()).toContain("Discard unsaved"); await dialog.dismiss(); });
  await page.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(title).toHaveValue("Keep these edits");
  page.once("dialog", async dialog => { expect(dialog.message()).toContain("Discard unsaved"); await dialog.dismiss(); });
  await page.evaluate(() => history.back());
  await expect(page.getByRole("status").filter({ hasText: "Unsaved changes." })).toBeVisible();
  await expect(dataset).toHaveValue("units\n3");
  page.once("dialog", async dialog => { expect(dialog.type()).toBe("beforeunload"); await dialog.dismiss(); });
  await page.reload().catch(() => {});
  await expect(title).toHaveValue("Keep these edits");
  await page.getByRole("checkbox", { name: "units", exact: true }).check();
  // Saving invalid input keeps both input and protection.
  await page.getByLabel("Maximum budget (testnet NEAR)").fill("invalid");
  await page.getByRole("button", { name: "Create private mission", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Enter a NEAR amount" })).toBeVisible();
  await expect(title).toHaveValue("Keep these edits");
  await page.getByLabel("Maximum budget (testnet NEAR)").fill("10");
  const unexpected = (dialog: import("@playwright/test").Dialog) => { void dialog.dismiss(); throw new Error(`Unexpected dialog: ${dialog.message()}`); };
  page.on("dialog", unexpected);
  await page.getByRole("button", { name: "Create private mission", exact: true }).click();
  await expect(page).toHaveURL(/\/missions\/(?!new$)[a-z0-9]+$/);
  await page.getByRole("button", { name: "Edit mission", exact: true }).click();
  await title.fill("Changed");
  await title.fill("Keep these edits");
  await expect(page.getByRole("status").filter({ hasText: "No unsaved changes." })).toBeVisible();
  await page.getByRole("button", { name: "Cancel editing", exact: true }).click();
  page.off("dialog", unexpected);
  await page.getByRole("button", { name: "Edit mission", exact: true }).click();
  await title.fill("Discard this");
  page.once("dialog", async dialog => { await dialog.dismiss(); });
  await page.getByRole("button", { name: "Cancel editing", exact: true }).click();
  await expect(title).toHaveValue("Discard this");
  page.once("dialog", async dialog => { await dialog.accept(); });
  await page.getByRole("button", { name: "Cancel editing", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Keep these edits", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit mission", exact: true }).click();
  await title.fill("Discard with Back");
  page.once("dialog", async dialog => { await dialog.accept(); });
  await page.evaluate(() => history.back());
  await expect(page).toHaveURL(/\/missions\/new$/);
  await expect(title).toHaveValue("");
  await title.fill("Discard with link");
  page.once("dialog", async dialog => { await dialog.accept(); });
  await page.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
});
